let defaultBundle: CatalogBundle | undefined;

/** The English bundle a renderer falls back to when no resolved catalog is passed. */
export function defaultCatalog(): CatalogBundle {
	defaultBundle ??= resolveCatalog("en").bundle;
	return defaultBundle;
}

function plainArguments(
	args: Readonly<Record<string, HumanMessageValue>> | undefined,
): Record<string, string | number> | undefined {
	if (args === undefined) return undefined;
	const plain: Record<string, string | number> = {};
	for (const [name, value] of Object.entries(args)) {
		plain[name] = typeof value === "object" ? value.value : value;
	}
	return plain;
}

/**
 * Render one catalog message as plain text without wrapping.
 *
 * The pre-runtime error and help paths write one `console.error`/`console.log`
 * argument, so they need the unwrapped string. A `ProtectedValue` argument is
 * unwrapped to its text, matching the legacy `resolveHumanMessage` behavior.
 */
export function catalogText(
	bundle: CatalogBundle,
	id: string,
	args?: Readonly<Record<string, HumanMessageValue>>,
): string {
	return bundle.format(id, plainArguments(args));
}

/**
 * The catalog identity of one human message.
 *
 * A message-bearing API takes this type instead of a plain `string`, so a
 * literal sentence does not type-check: the ID is the contract, and the text
 * comes from the resolved catalog. The report is built from `defaultCatalog()`,
 * so a `--json` field keeps its English value while the human renderer is the
 * only reader of the resolved locale.
 */
export interface CatalogMessageRef {
	readonly id: CatalogMessageId;
	readonly args?: Readonly<Record<string, HumanMessageValue>>;
}

/** Build a catalog message reference. */
export function catalogMessage(
	id: CatalogMessageId,
	args?: Readonly<Record<string, HumanMessageValue>>,
): CatalogMessageRef {
	return args === undefined ? { id } : { id, args };
}

/** Render a catalog message reference in the given bundle. */
export function catalogMessageText(bundle: CatalogBundle, message: CatalogMessageRef): string {
	return catalogText(bundle, message.id, message.args);
}

/**
 * An error whose message is a catalog ID.
 *
 * `Error.message` is the English text, so a generic catch still prints English,
 * while the descriptor lets `handleMainCliError` render the resolved locale
 * through the outer `jouzu.cli.error.generic` wrapper.
 */
export class CatalogError extends Error {
	readonly catalogMessage: CatalogMessageRef;

	constructor(message: CatalogMessageRef) {
		super(catalogMessageText(defaultCatalog(), message));
		this.name = "CatalogError";
		this.catalogMessage = message;
	}
}

/** Resolve a label by a field's stable id, keeping the report's label when unmapped. */
export function catalogFieldLabel(bundle: CatalogBundle, id: string, fallback: string): string {
	const messageId = DOCTOR_FIELD_LABEL_IDS[id] ?? CATALOG_FIELD_LABEL_IDS[id];
	return messageId === undefined ? fallback : catalogText(bundle, messageId);
}
