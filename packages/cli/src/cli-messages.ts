/**
 * The catalog message IDs for the pre-runtime CLI text.
 *
 * These IDs are catalog-only: they have no entry in `human-messages.ts`, whose
 * `CliMessageId` table and English table remain the byte-identity oracle for
 * the pre-existing error and argument messages. The catalog is the source of
 * truth for these new messages, so the English output lives in
 * `locales/en/cli.ftl` and the identifier rule (a stable dotted ID has no
 * hyphen) is enforced by `scripts/check-locales.mjs` for this table too.
 *
 * `defaultCatalog` resolves the English bundle once, so a renderer called
 * without a resolved catalog (a unit test, for example) still renders from the
 * catalog rather than from a second copy of the English text.
 */

